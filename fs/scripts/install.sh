#!/usr/bin/env bash
# Install the fs binary, a default config, and (where available) an
# OS service definition (systemd on Linux, launchd on macOS).
#
# Usage:
#   scripts/install.sh                 # user install (~/.local/bin, no sudo)
#   scripts/install.sh --system        # system-wide install (requires sudo)
#   scripts/install.sh --uninstall     # reverse a previous install
#   scripts/install.sh --system --uninstall
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

SYSTEM=0
UNINSTALL=0
for arg in "$@"; do
    case "$arg" in
        --system)    SYSTEM=1 ;;
        --uninstall) UNINSTALL=1 ;;
        *) echo "unknown argument: $arg" >&2; exit 1 ;;
    esac
done

os="$(uname -s)"

if [ "$SYSTEM" -eq 1 ]; then
    BIN_DIR="/usr/local/bin"
    CONFIG_DIR="/etc/fs"
    DATA_DIR="/var/lib/fs"
    LOG_DIR="/var/log/fs"
    EXT_DIR="/usr/local/lib/fs/extensions"
    SUDO="sudo"
else
    BIN_DIR="$HOME/.local/bin"
    CONFIG_DIR="$HOME/.config/fs"
    DATA_DIR="$HOME/.local/share/fs"
    LOG_DIR="$HOME/.local/state/fs/logs"
    EXT_DIR="$HOME/.local/share/fs/extensions"
    SUDO=""
fi

CONFIG_FILE="$CONFIG_DIR/config.toml"
BIN_PATH="$BIN_DIR/fsd"
CLIENT_PATH="$BIN_DIR/fs"

# ---------------------------------------------------------------------------
# Uninstall
# ---------------------------------------------------------------------------
if [ "$UNINSTALL" -eq 1 ]; then
    case "$os" in
        Linux)
            if [ "$SYSTEM" -eq 1 ]; then
                UNIT="/etc/systemd/system/fs.service"
                $SUDO systemctl disable --now fs 2>/dev/null || true
                $SUDO rm -f "$UNIT"
                $SUDO systemctl daemon-reload
            else
                UNIT="$HOME/.config/systemd/user/fs.service"
                systemctl --user disable --now fs 2>/dev/null || true
                rm -f "$UNIT"
                systemctl --user daemon-reload 2>/dev/null || true
            fi
            ;;
        Darwin)
            if [ "$SYSTEM" -eq 1 ]; then
                PLIST="/Library/LaunchDaemons/com.fs.daemon.plist"
                $SUDO launchctl bootout system "$PLIST" 2>/dev/null || true
                $SUDO rm -f "$PLIST"
            else
                PLIST="$HOME/Library/LaunchAgents/com.fs.daemon.plist"
                launchctl bootout "gui/$(id -u)" "$PLIST" 2>/dev/null || true
                rm -f "$PLIST"
            fi
            ;;
    esac
    $SUDO rm -f "$BIN_PATH" "$CLIENT_PATH"
    $SUDO rm -rf "$EXT_DIR"
    echo "==> Removed $BIN_PATH, $CLIENT_PATH and the service definition."
    echo "==> Config and data left in place: $CONFIG_DIR, $DATA_DIR"
    exit 0
fi

# ---------------------------------------------------------------------------
# Install
# ---------------------------------------------------------------------------
if [ ! -x "../target/release/fsd" ]; then
    echo "../target/release/fsd not found. Run scripts/build.sh first." >&2
    exit 1
fi

echo "==> Installing binaries to $BIN_DIR"
$SUDO mkdir -p "$BIN_DIR" "$CONFIG_DIR" "$DATA_DIR" "$LOG_DIR"
$SUDO cp ../target/release/fsd "$BIN_PATH"
$SUDO chmod 755 "$BIN_PATH"
$SUDO cp ../target/release/fs "$CLIENT_PATH"
$SUDO chmod 755 "$CLIENT_PATH"

if [ -x ../target/release/fs-ext-rar2zip ]; then
    echo "==> Installing rar2zip extension to $EXT_DIR/rar2zip"
    $SUDO mkdir -p "$EXT_DIR/rar2zip"
    $SUDO chmod 755 "$EXT_DIR" "$EXT_DIR/rar2zip"
    $SUDO cp ../target/release/fs-ext-rar2zip crates/fs-ext-rar2zip/extension.toml "$EXT_DIR/rar2zip/"
    $SUDO chmod 755 "$EXT_DIR/rar2zip/fs-ext-rar2zip"
    $SUDO chmod 644 "$EXT_DIR/rar2zip/extension.toml"
    echo "==> To enable it, add to the top of $CONFIG_FILE: extensions_dir = \"$EXT_DIR\""
fi

if [ -x ../target/release/fs-ext-sftpd ]; then
    echo "==> Installing sftpd extension to $EXT_DIR/sftpd"
    $SUDO mkdir -p "$EXT_DIR/sftpd"
    $SUDO chmod 755 "$EXT_DIR" "$EXT_DIR/sftpd"
    $SUDO cp ../target/release/fs-ext-sftpd crates/fs-ext-sftpd/extension.toml "$EXT_DIR/sftpd/"
    $SUDO chmod 755 "$EXT_DIR/sftpd/fs-ext-sftpd"
    $SUDO chmod 644 "$EXT_DIR/sftpd/extension.toml"
    echo "==> To enable it, set extensions_dir = \"$EXT_DIR\" and add an [extensions.sftpd] section (see crates/fs-ext-sftpd/config.toml)"
fi

if [ ! -f "$CONFIG_FILE" ]; then
    echo "==> Writing default config to $CONFIG_FILE (edit watch_paths before starting)"
    $SUDO tee "$CONFIG_FILE" > /dev/null <<EOF
# fs config - generated by scripts/install.sh.
# Edit watch_paths, then run: fsd --config $CONFIG_FILE validate-config

watch_paths = ["$HOME"]
data_dir    = "$DATA_DIR"
log_dir     = "$LOG_DIR"

[api]
rest_port = 7700
grpc_port = 7701
EOF
else
    echo "==> Config already exists at $CONFIG_FILE, leaving it untouched"
fi

case "$os" in
    Linux)
        if ! command -v systemctl >/dev/null 2>&1; then
            echo "==> systemctl not found; skipping service setup. Use scripts/run.sh to start fs."
        else
            if [ "$SYSTEM" -eq 1 ]; then
                UNIT_DIR="/etc/systemd/system"
                UNIT="$UNIT_DIR/fs.service"
                SYSTEMCTL="$SUDO systemctl"
            else
                UNIT_DIR="$HOME/.config/systemd/user"
                UNIT="$UNIT_DIR/fs.service"
                SYSTEMCTL="systemctl --user"
                mkdir -p "$UNIT_DIR"
            fi
            echo "==> Writing systemd unit to $UNIT"
            $SUDO tee "$UNIT" > /dev/null <<EOF
[Unit]
Description=Fs Daemon
After=network.target

[Service]
Type=notify
ExecStart=$BIN_PATH --config $CONFIG_FILE daemon
Restart=on-failure

[Install]
WantedBy=$([ "$SYSTEM" -eq 1 ] && echo "multi-user.target" || echo "default.target")
EOF
            $SYSTEMCTL daemon-reload
            $SYSTEMCTL enable --now fs
            echo "==> Service started. Check with: $SYSTEMCTL status fs"
        fi
        ;;
    Darwin)
        LABEL="com.fs.daemon"
        if [ "$SYSTEM" -eq 1 ]; then
            PLIST_DIR="/Library/LaunchDaemons"
            DOMAIN="system"
        else
            PLIST_DIR="$HOME/Library/LaunchAgents"
            DOMAIN="gui/$(id -u)"
            mkdir -p "$PLIST_DIR"
        fi
        PLIST="$PLIST_DIR/$LABEL.plist"
        echo "==> Writing launchd plist to $PLIST"
        $SUDO tee "$PLIST" > /dev/null <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
    "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$BIN_PATH</string>
        <string>--config</string>
        <string>$CONFIG_FILE</string>
        <string>daemon</string>
    </array>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
    <key>StandardOutPath</key><string>$LOG_DIR/stdout.log</string>
    <key>StandardErrorPath</key><string>$LOG_DIR/stderr.log</string>
</dict>
</plist>
EOF
        $SUDO launchctl bootout "$DOMAIN" "$PLIST" 2>/dev/null || true
        $SUDO launchctl bootstrap "$DOMAIN" "$PLIST"
        echo "==> Service loaded. Check with: launchctl list | grep $LABEL"
        ;;
    *)
        echo "==> Unrecognized platform '$os'; skipping service setup. Use scripts/run.sh to start fs."
        ;;
esac

echo "==> Install complete. Edit $CONFIG_FILE, then validate with:"
echo "      $BIN_PATH --config $CONFIG_FILE validate-config"
