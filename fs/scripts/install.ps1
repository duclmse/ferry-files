#Requires -Version 5.1
# Install filesearch (and optionally rar2zip) built by scripts\build.ps1.
#
# Usage:
#   scripts\install.ps1                       # copy filesearch.exe + config only
#   scripts\install.ps1 -Service               # also register the Windows Service (needs admin)
#   scripts\install.ps1 -Service -WithRar2zip   # also install rar2zip via its install-service.ps1 (needs admin)
#   scripts\install.ps1 -Uninstall              # reverse a previous install
param(
    [string]$Prefix = "$env:ProgramFiles\filesearch",
    [switch]$Service,
    [switch]$WithRar2zip,
    [switch]$Uninstall
)

$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

function Test-Admin {
    $principal = New-Object Security.Principal.WindowsPrincipal(
        [Security.Principal.WindowsIdentity]::GetCurrent())
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

$dataDir   = "$env:ProgramData\filesearch"
$configFile = Join-Path $Prefix "config.toml"
$exePath    = Join-Path $Prefix "filesearch.exe"

if ($Uninstall) {
    if (-not (Test-Admin)) {
        Write-Error "Uninstalling the service requires an elevated (Administrator) PowerShell session."
        exit 1
    }
    if (Get-Service FilesearchDaemon -ErrorAction SilentlyContinue) {
        Stop-Service FilesearchDaemon -ErrorAction SilentlyContinue
        & $exePath uninstall-service
    }
    if ($WithRar2zip -and (Get-Service rar2zip -ErrorAction SilentlyContinue)) {
        & (Join-Path "crates\rar2zip" "install-service.ps1") -Uninstall
    }
    Remove-Item -Recurse -Force $Prefix -ErrorAction SilentlyContinue
    Write-Host "==> Removed $Prefix and its service registration(s)."
    Write-Host "==> Data left in place: $dataDir"
    exit 0
}

if (($Service -or $WithRar2zip) -and -not (Test-Admin)) {
    Write-Error "Registering a Windows Service requires an elevated (Administrator) PowerShell session."
    exit 1
}

if (-not (Test-Path "target\release\filesearch.exe")) {
    Write-Error "target\release\filesearch.exe not found. Run scripts\build.ps1 first."
    exit 1
}

Write-Host "==> Installing to $Prefix"
New-Item -ItemType Directory -Force -Path $Prefix | Out-Null
New-Item -ItemType Directory -Force -Path "$dataDir\data" | Out-Null
New-Item -ItemType Directory -Force -Path "$dataDir\logs" | Out-Null
Copy-Item "target\release\filesearch.exe" $exePath -Force

if (-not (Test-Path $configFile)) {
    Write-Host "==> Writing default config to $configFile (edit watch_paths before starting)"
    @"
# filesearch config - generated by scripts\install.ps1.
# Edit watch_paths, then run: filesearch.exe --config $configFile validate-config

watch_paths = ["$env:USERPROFILE"]
data_dir    = "$dataDir\data"
log_dir     = "$dataDir\logs"

[api]
rest_port = 7700
grpc_port = 7701
"@ | Set-Content -Path $configFile -Encoding UTF8
} else {
    Write-Host "==> Config already exists at $configFile, leaving it untouched"
}

if ($Service) {
    Write-Host "==> Registering FilesearchDaemon service"
    & $exePath --config $configFile install-service
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    Start-Service FilesearchDaemon
    Write-Host "==> Service started. Check with: Get-Service FilesearchDaemon"
} else {
    Write-Host "==> Skipped service registration. Run scripts\run.ps1, or re-run with -Service."
}

if ($WithRar2zip) {
    if (-not (Test-Path "target\release\rar2zip.exe")) {
        Write-Error "target\release\rar2zip.exe not found. Run scripts\build.ps1 first."
        exit 1
    }
    Copy-Item "target\release\rar2zip.exe" (Join-Path $Prefix "rar2zip.exe") -Force
    $rar2zipConfig = Join-Path $Prefix "rar2zip.toml"
    if (-not (Test-Path $rar2zipConfig)) {
        Write-Host "==> No rar2zip.toml found; copy one to $rar2zipConfig before starting the service."
    }
    Write-Host "==> Registering rar2zip service via its install-service.ps1"
    & (Join-Path "crates\rar2zip" "install-service.ps1") `
        -BinaryPath (Join-Path $Prefix "rar2zip.exe") `
        -ConfigPath $rar2zipConfig
}

Write-Host "==> Install complete. Edit $configFile, then validate with:"
Write-Host "      $exePath --config $configFile validate-config"
