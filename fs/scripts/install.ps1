#Requires -Version 5.1
# Install fsd and fs built by scripts\build.ps1.
#
# Usage:
#   scripts\install.ps1                       # copy fsd.exe, fs.exe + config only
#   scripts\install.ps1 -Service               # also register the Windows Service (needs admin)
#   scripts\install.ps1 -Uninstall              # reverse a previous install
param(
    [string]$Prefix = "$env:ProgramFiles\fs",
    [switch]$Service,
    [switch]$Uninstall
)

$ErrorActionPreference = "Stop"
Set-Location (Join-Path $PSScriptRoot "..")

function Test-Admin {
    $principal = New-Object Security.Principal.WindowsPrincipal(
        [Security.Principal.WindowsIdentity]::GetCurrent())
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

$dataDir   = "$env:ProgramData\fs"
$configFile = Join-Path $Prefix "config.toml"
$exePath    = Join-Path $Prefix "fsd.exe"

if ($Uninstall) {
    if (-not (Test-Admin)) {
        Write-Error "Uninstalling the service requires an elevated (Administrator) PowerShell session."
        exit 1
    }
    if (Get-Service FsDaemon -ErrorAction SilentlyContinue) {
        Stop-Service FsDaemon -ErrorAction SilentlyContinue
        & $exePath uninstall-service
    }
    Remove-Item -Recurse -Force $Prefix -ErrorAction SilentlyContinue
    Write-Host "==> Removed $Prefix and its service registration."
    Write-Host "==> Data left in place: $dataDir"
    exit 0
}

if ($Service -and -not (Test-Admin)) {
    Write-Error "Registering a Windows Service requires an elevated (Administrator) PowerShell session."
    exit 1
}

if (-not (Test-Path "target\release\fsd.exe")) {
    Write-Error "target\release\fsd.exe not found. Run scripts\build.ps1 first."
    exit 1
}

Write-Host "==> Installing to $Prefix"
New-Item -ItemType Directory -Force -Path $Prefix | Out-Null
New-Item -ItemType Directory -Force -Path "$dataDir\data" | Out-Null
New-Item -ItemType Directory -Force -Path "$dataDir\logs" | Out-Null
Copy-Item "target\release\fsd.exe" $exePath -Force
Copy-Item "target\release\fs.exe" (Join-Path $Prefix "fs.exe") -Force

if (Test-Path "target\release\fs-ext-rar2zip.exe") {
    $extDir = Join-Path $Prefix "extensions\rar2zip"
    Write-Host "==> Installing rar2zip extension to $extDir"
    New-Item -ItemType Directory -Force -Path $extDir | Out-Null
    Copy-Item "target\release\fs-ext-rar2zip.exe" $extDir -Force
    Copy-Item "crates\fs-ext-rar2zip\extension.toml" $extDir -Force
    Write-Host "==> To enable it, add to the top of $configFile: extensions_dir = '$Prefix\extensions'"
}

if (-not (Test-Path $configFile)) {
    Write-Host "==> Writing default config to $configFile (edit watch_paths before starting)"
    @"
# fs config - generated by scripts\install.ps1.
# Edit watch_paths, then run: fsd.exe --config $configFile validate-config

watch_paths = ["$env:USERPROFILE"]
data_dir    = "$dataDir\data"
log_dir     = "$dataDir\logs"

[api]
rest_port = 7700
grpc_port = 7701
"@ | Set-Content -Path $configFile -Encoding UTF8
} else {
    Write-Host "==> Config already exists at $configFile, leaving it untouched"
}

if ($Service) {
    Write-Host "==> Registering FsDaemon service"
    & $exePath --config $configFile install-service
    if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }
    Start-Service FsDaemon
    Write-Host "==> Service started. Check with: Get-Service FsDaemon"
} else {
    Write-Host "==> Skipped service registration. Run scripts\run.ps1, or re-run with -Service."
}

Write-Host "==> Install complete. Edit $configFile, then validate with:"
Write-Host "      $exePath --config $configFile validate-config"
